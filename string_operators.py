"""
Escape sequences - often called operators or special characters
combinations of characters starting
with a backsplash(\) that represent special whitespace
 or control characters inside strings
"""
#\n-(Newline): moves the cursor to a new line
print("Example to '\\n'\nI'm in new line but in same printing")

#\t(Tab)- added horizontal tab space
print("Example to \ t")
print("Name:\tRon")

# \b- Backspace
print("arowkvcy\b\b\b\besc")

#literal backslash (\\)
print("c:\\users\\ron\\desktop")

#combined inside a string (' and ")
print ('It\'s a python script!')
print("massage from python:\"you are champions\"")